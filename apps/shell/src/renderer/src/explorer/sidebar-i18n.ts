export function sidebarText(
  lang: string,
  text: string,
  params: Record<string, string | number> = {},
): string {
  const tabIndex = ['Chat', 'Knowledge', 'Models'].indexOf(text)
  const translated =
    lang === 'ar' ? sidebarArabic[text] : tabIndex >= 0 ? tabs[lang]?.[tabIndex] : undefined
  return (translated ?? text).replace(/\{(\w+)\}/g, (match, key: string) =>
    String(params[key] ?? match),
  )
}
export function useSidebarText() {
  const { lang } = useI18n()
  return {
    s: (text: string, params?: Record<string, string | number>) => sidebarText(lang, text, params),
    dir: lang === 'ar' || lang === 'he' ? ('rtl' as const) : ('ltr' as const),
  }
}
